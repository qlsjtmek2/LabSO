// 챔피언 ID로 메타데이터 가져오기
export function getChampionMeta(championId: string): ChampionMeta | undefined {
  return CHAMPION_META[championId];
}

// 모든 챔피언 메타데이터 목록
export function getAllChampionMeta(): ChampionMeta[] {
  return Object.values(CHAMPION_META);
}

// 특정 라인의 챔피언들 가져오기
export function getChampionsByLane(lane: string): ChampionMeta[] {
  return Object.values(CHAMPION_META).filter((c) => c.lanes.includes(lane as any));
}

// 특정 클래스의 챔피언들 가져오기
export function getChampionsByClass(championClass: string): ChampionMeta[] {
  return Object.values(CHAMPION_META).filter(
    (c) => c.class === championClass || c.subClass === championClass
  );
}

// 챔피언 메타데이터 존재 여부 확인
export function hasChampionMeta(championId: string): boolean {
  return championId in CHAMPION_META;
}
